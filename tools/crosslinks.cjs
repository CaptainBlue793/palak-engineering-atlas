'use strict';
/* Writes the "Related chapters in other courses" block into each chapter, from the topic map in
   tools/crosslinks-map.cjs. Run from any directory.

     node tools/crosslinks.cjs apply     rewrite every block (safe to re-run: blocks are replaced)
     node tools/crosslinks.cjs check     exit 1 if a reference is wrong or a block is out of date
     node tools/crosslinks.cjs report    how many chapters link out, per course, and which don't

   The block sits just above the chapter's key takeaways, between two marker comments. Its title
   uses class="title xref-t" on purpose: build-study-data.js indexes <div class="title"> exactly,
   and the same heading on every chapter would only add noise to search. */
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const REG = require('./registry.cjs');
const { COURSE, TOPICS } = require('./crosslinks-map.cjs');

const ROOT = REG.ROOT;
const START = '<!-- xref:start (generated by tools/crosslinks.cjs from tools/crosslinks-map.cjs; do not edit by hand) -->';
const END = '<!-- xref:end -->';
const BLOCK = /[ \t]*<!-- xref:start[^>]*-->[\s\S]*?<!-- xref:end -->\r?\n/;
const ANCHOR = /^([ \t]*)<div class="takeaways">/m;
const mode = process.argv[2] || 'check';

const problems = [];
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/* ---------- every course's chapter registry ---------- */
const courses = REG.COURSES.filter((c) => Object.values(COURSE).includes(c.dir));
const chapters = {};   // dir -> [{ n, file, title }]
for (const c of courses) {
  const app = fs.readFileSync(path.join(ROOT, c.dir, 'assets/app.js'), 'utf8');
  chapters[c.dir] = vm.runInNewContext(app.match(/const CHAPTERS = (\[[\s\S]*?\n  \]);/)[1]);
}
const order = courses.map((c) => c.dir);

function resolve(ref) {
  const [alias, num] = ref.split('/');
  const dir = COURSE[alias];
  if (!dir || !chapters[dir]) { problems.push('unknown course in "' + ref + '"'); return null; }
  const ch = chapters[dir].find((x) => x.file.startsWith(num + '-'));
  if (!ch) { problems.push('no chapter for "' + ref + '"'); return null; }
  const course = courses.find((c) => c.dir === dir);
  // The hub's short name, except where it only reads well next to a card ("Distributed").
  const name = course.short === 'Distributed' ? 'Distributed Systems' : course.short;
  return { key: dir + '/' + ch.file, dir, file: ch.file, n: ch.n, title: ch.title, course: name };
}

/* ---------- topic map -> for each chapter, the topics it belongs to ---------- */
const seenLabels = new Set();
const topics = [];
for (const [label, refs] of TOPICS) {
  if (seenLabels.has(label)) problems.push('duplicate topic "' + label + '"');
  seenLabels.add(label);
  const members = refs.map(resolve).filter(Boolean);
  if (new Set(members.map((m) => m.key)).size !== members.length) problems.push('"' + label + '" lists a chapter twice');
  if (new Set(members.map((m) => m.dir)).size < 2) problems.push('"' + label + '" needs chapters from at least two courses');
  members.sort((a, b) => order.indexOf(a.dir) - order.indexOf(b.dir) || a.n - b.n);
  topics.push({ label, members });
}

const label = (m) => (m.n < 1 ? 'P' + Math.round(m.n * 10) : 'Ch ' + m.n) + ': ' + m.title;
const link = (m) => '<a href="../' + m.dir + '/' + m.file + '">' + esc(label(m)) + '</a>';

function blockFor(dir, file, indent, eol) {
  const rows = [];
  for (const t of topics) {
    if (!t.members.some((m) => m.dir === dir && m.file === file)) continue;
    const others = t.members.filter((m) => m.dir !== dir);
    if (!others.length) continue;
    // One group per course: "Databases Ch 13 · Ch 14; LLD Ch 26". Chapter titles contain commas, so
    // links are separated by a middle dot and courses by a semicolon.
    const groups = order.map((d) => others.filter((m) => m.dir === d)).filter((g) => g.length)
      .map((g) => esc(g[0].course) + ' ' + g.map(link).join(' · '));
    rows.push('<li><b>' + esc(t.label) + ':</b> ' + groups.join('; ') + '</li>');
  }
  if (!rows.length) return '';
  const lines = [
    START,
    '<div class="callout xref">',
    '  <div class="ico">🧭</div>',
    '  <div class="body"><div class="title xref-t">Related chapters in other courses</div>',
    '    <ul class="mb0">',
    ...rows.map((r) => '      ' + r),
    '    </ul>',
    '  </div>',
    '</div>',
    END,
  ];
  return lines.map((l) => indent + l).join(eol) + eol;
}

/* ---------- walk every chapter ---------- */
let withBlock = 0, changed = 0, links = 0;
const perCourse = {}, none = {};
for (const dir of order) {
  perCourse[dir] = 0; none[dir] = [];
  for (const ch of chapters[dir]) {
    const p = path.join(ROOT, dir, ch.file);
    const src = fs.readFileSync(p, 'utf8');
    const eol = src.includes('\r\n') ? '\r\n' : '\n';
    const bare = src.replace(BLOCK, '');
    const at = bare.match(ANCHOR);
    if (!at) { problems.push(dir + '/' + ch.file + ': no <div class="takeaways"> to anchor the block'); continue; }
    const block = blockFor(dir, ch.file, at[1], eol);
    const next = block ? bare.slice(0, at.index) + block + bare.slice(at.index) : bare;
    if (block) { withBlock++; perCourse[dir]++; links += (block.match(/<a href=/g) || []).length; } else none[dir].push(ch.file);
    if (next !== src) {
      changed++;
      if (mode === 'apply') fs.writeFileSync(p, next);
      else if (mode === 'check') problems.push(dir + '/' + ch.file + ': related-chapters block is out of date (run: node tools/crosslinks.cjs apply)');
    }
  }
}

if (mode === 'report') {
  for (const dir of order) {
    console.log(dir.padEnd(22) + String(perCourse[dir]).padStart(3) + ' of ' + chapters[dir].length + ' chapters link to other courses');
    if (none[dir].length) console.log('    none: ' + none[dir].map((f) => f.replace('.html', '')).join(', '));
  }
}
problems.forEach((p) => console.log('ERROR ' + p));
console.log(topics.length + ' topics; ' + withBlock + ' chapters carry a block with ' + links + ' links; ' +
  (mode === 'apply' ? changed + ' files rewritten' : changed + ' files differ from the map') + '; ' + problems.length + ' errors.');
process.exitCode = problems.length ? 1 : 0;
